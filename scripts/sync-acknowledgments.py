"""Refresh website credits from the app: python3 scripts/sync-acknowledgments.py.
The generated file is committed so website builds don't require the app checkout.
"""
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
app = root.parent / 'Qum/Qum'
preferences = (app / 'Models/SettingsPreferences.swift').read_text()
credits = (app / 'Models/RecitationCredits.swift').read_text()
places = dict(re.findall(r'case \.(\w+):\s*String\(localized: "([^"]+)"', preferences))
section = preferences.split('var attribution: Attribution?', 1)[1].split('struct Attribution', 1)[0]
entries = []
for match in re.finditer(r'case \.(\w+):\s*Attribution\(\s*reciter: "([^"]+)",\s*licence: "([^"]+)",\s*licenceURL: "([^"]+)",\s*source: "([^"]+)"\s*\)', section):
    key, reciter, licence, licence_url, source_url = match.groups()
    assert licence_url.startswith('https://') and source_url.startswith('https://')
    entries.append(dict(id=key, place=places[key], reciter=reciter, licence=licence, licenceURL=licence_url, sourceURL=source_url))
assert len(entries) == section.count('Attribution('), 'An attribution could not be parsed'
assert entries, 'No credits found'
notice = re.search(r'static var modificationNotice: String.*?localized: "([^"]+)"', credits, re.S)
assert notice, 'Modification notice missing'
data = dict(entries=entries, modificationNotice=notice[1])
(root / 'src/data/acknowledgments.ts').write_text('// Generated by scripts/sync-acknowledgments.py from the app attribution records.\nexport const acknowledgments = ' + json.dumps(data, ensure_ascii=False, indent=4) + ' as const;\n')
print(f'Synchronized {len(entries)} recording credits and modification notice')
